# Chapter 2 - Variables and Data Types

# Variable is a container
a = 30
b = "Nikki"
c = 71.22
print(a)
print(b)
print(c)

# Data Types
x = 71
y = 88.44
name = "Nikki"
print(type(x))
print(type(y))
print(type(name))

# Variable Rules
my_name = "Nikki"
one8 = 18
seven_ = 7
_seven = 7

# Operators
print(10 + 3)
print(10 - 3)
print(10 * 3)
print(10 / 3)

a = 5
a += 2
print(a)

print(10 == 3)
print(True and False)

# Typecasting
print(str(31))
print(int("32"))
print(float(32))

# input() function - always returns string
user_name = input("Enter name: ")
